// got renders symbols as "kind name key line", one per entry, key left
// out when it equals the name.
func got(syms []Symbol) []string {
	var out []string
	for _, s := range syms {
		if s.Key != s.Name {
			out = append(out, fmt.Sprintf("%s %s %s %d", s.Kind, s.Name, s.Key, s.Line))
			continue
		}
		out = append(out, fmt.Sprintf("%s %s %d", s.Kind, s.Name, s.Line))
	}
	return out
}

