func TestSkip(t *testing.T) {
	tests := []struct {
		path string
		size int64
		skip bool
	}{
		{"main.go", 100, false},
		{"main.go", MaxFileBytes + 1, true},
		{"main.go", MaxFileBytes, false},
		{"vendor/x/y.go", 10, true},
		{"web/node_modules/a/index.js", 10, true},
		{"internal/vendors/y.go", 10, false},
		{"zz_gen.go", 10, true},
		{"api.pb.go", 10, true},
		{"static/app.min.js", 10, true},
		{"static/app.js", 10, false},
		{"image.png", 10, true},
		{"Makefile", 10, true},
	}
	for _, tc := range tests {
		if got := Skip(tc.path, tc.size); got != tc.skip {
			t.Errorf("Skip(%q, %d) = %v, want %v", tc.path, tc.size, got, tc.skip)
		}
	}
}
